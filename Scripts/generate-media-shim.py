#!/usr/bin/env python3
"""Generates the system media decoders' page script from its sources.

Input:  Sources/CefRenderer/MediaShim/*.js, joined in the order of SOURCES
Output: Sources/CefRenderer/MediaShimScript.swift (generated — never edit it)

The script is one function expression, `(function (native) { … })`, which
`MediaShim` evaluates in a document's main world before its scripts run and
calls with CefSwift's `native` object, so the page's globals gain nothing.
Full-line comments and blank lines are left out of the output; the sources
keep them.

Usage:
  Scripts/generate-media-shim.py            # rewrite the generated file
  Scripts/generate-media-shim.py --check    # exit 1 if it is out of date (CI)
"""

import argparse
import pathlib
import re
import sys

ROOT = pathlib.Path(__file__).resolve().parent.parent
SOURCE_DIRECTORY = ROOT / "Sources/CefRenderer/MediaShim"
OUTPUT = ROOT / "Sources/CefRenderer/MediaShimScript.swift"
# Each file may use what the files before it define.
SOURCES = [
    "natives.js",        # the page's originals; native-looking replacements
    "codecs.js",         # which types the shim plays
    "mp4.js",            # ISO BMFF demuxer
    "adts.js",           # ADTS (.aac) parser
    "decoder.js",        # a stream decoded by the media service
    "source-buffer.js",  # MediaSource, SourceBuffer, canPlayType, Media Capabilities
    "media-element.js",  # <audio>/<video> files Chromium cannot play
]
BANNER = (
    "// GENERATED by Scripts/generate-media-shim.py from Sources/CefRenderer/MediaShim/*.js — do not edit.\n"
)
DELIMITER = "##"


def script() -> str:
    names = sorted(p.name for p in SOURCE_DIRECTORY.glob("*.js"))
    if names != sorted(SOURCES):
        sys.exit(f"generate-media-shim: SOURCES lists {sorted(SOURCES)}, the directory has {names}")
    lines = ["(function (native) {", "'use strict';"]
    for name in SOURCES:
        for line in (SOURCE_DIRECTORY / name).read_text().splitlines():
            if not line.strip() or re.match(r"^\s*//", line):
                continue
            lines.append(line.rstrip())
    lines.append("})")
    text = "\n".join(lines) + "\n"
    if f'"""{DELIMITER}' in text or "\\" + DELIMITER in text:
        sys.exit("generate-media-shim: the script contains the Swift raw string delimiter")
    return text


def swift(text: str) -> str:
    return (
        BANNER
        + "\n"
        + "/// The system media decoders' page script: a function expression that\n"
        + "/// `MediaShim` calls with its `native` object before a document's own\n"
        + "/// scripts run. See `Sources/CefRenderer/MediaShim/` and\n"
        + "/// `Scripts/generate-media-shim.py`.\n"
        + "enum MediaShimScript {\n"
        + "    /// The script's UTF-8, which lives as long as the process.\n"
        + "    static var source: UnsafeRawBufferPointer {\n"
        + "        UnsafeRawBufferPointer(start: text.utf8Start, count: text.utf8CodeUnitCount)\n"
        + "    }\n"
        + "\n"
        + f'    private static let text: StaticString = {DELIMITER}"""\n'
        + text
        + f'"""{DELIMITER}\n'
        + "}\n"
    )


def main() -> None:
    parser = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    parser.add_argument("--check", action="store_true", help="fail if the generated file is out of date")
    arguments = parser.parse_args()
    generated = swift(script())
    if arguments.check:
        current = OUTPUT.read_text() if OUTPUT.exists() else ""
        if current != generated:
            sys.exit(f"generate-media-shim: {OUTPUT.relative_to(ROOT)} is out of date; run Scripts/generate-media-shim.py")
        print(f"{OUTPUT.relative_to(ROOT)} is up to date.")
        return
    OUTPUT.write_text(generated)
    print(f"Wrote {OUTPUT.relative_to(ROOT)} ({len(generated)} bytes).")


if __name__ == "__main__":
    main()
