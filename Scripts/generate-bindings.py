#!/usr/bin/env python3
"""Regenerates the CCef C bridge from the vendored CEF headers.

Outputs (both are generated files — never edit them by hand):

  Sources/CCef/include/ccef_capi.h     umbrella #include of every C API header
  Sources/CCef/include/ccef_symbols.h  X-macro list of every exported cef_* global

The symbol list is produced by running the real C preprocessor over the
umbrella header with the pinned CEF_API_VERSION, then collecting every
declaration marked CEF_EXPORT. That makes API-version gating exact: a function
that the pinned version does not expose is never declared, so it is never bound.

Run after bumping CEF or changing CEF_API_VERSION:

  Scripts/generate-bindings.py          # rewrite the generated files
  Scripts/generate-bindings.py --check  # exit 1 if they are out of date (CI)
"""

import re
import subprocess
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
INCLUDE = ROOT / "Sources" / "CCef" / "include"
CAPI_H = INCLUDE / "ccef_capi.h"
SYMBOLS_H = INCLUDE / "ccef_symbols.h"

# Internal headers that are C-safe and declare types or exported functions.
INTERNAL_HEADERS = [
    "include/cef_api_hash.h",
    "include/cef_version_info.h",
    "include/cef_command_ids.h",
    "include/cef_id_mappers.h",
    "include/cef_pack_strings.h",
    "include/internal/cef_string.h",
    "include/internal/cef_string_list.h",
    "include/internal/cef_string_map.h",
    "include/internal/cef_string_multimap.h",
    "include/internal/cef_time.h",
    "include/internal/cef_types.h",
    "include/internal/cef_logging_internal.h",
    "include/internal/cef_thread_internal.h",
    "include/internal/cef_trace_event_internal.h",
]

# Test-only C API; never shipped to embedders.
EXCLUDED_DIRS = {"test"}

GENERATED_BANNER = "// GENERATED by Scripts/generate-bindings.py — do not edit.\n"

EXPORT_MARK = "CCEF_EXPORT_MARK"


def capi_headers():
    capi = INCLUDE / "include" / "capi"
    found = []
    for path in sorted(capi.rglob("*.h")):
        relative = path.relative_to(INCLUDE)
        if EXCLUDED_DIRS & set(relative.parts):
            continue
        found.append(relative.as_posix())
    return found


def render_capi_header():
    lines = [
        GENERATED_BANNER,
        "// Umbrella include of the CEF C API at the pinned CEF_API_VERSION.\n",
        "#ifndef CCEF_CAPI_H_\n#define CCEF_CAPI_H_\n\n",
        '#include "ccef_config.h"\n\n',
    ]
    lines += [f'#include "{h}"\n' for h in INTERNAL_HEADERS if (INCLUDE / h).exists()]
    lines.append("\n")
    lines += [f'#include "{h}"\n' for h in capi_headers()]
    lines.append("\n#endif  // CCEF_CAPI_H_\n")
    return "".join(lines)


def preprocess(capi_source):
    """Preprocesses the umbrella header, tagging exports with EXPORT_MARK."""
    source = (
        # cef_export.h is include-guarded; pre-defining the guard lets us supply
        # our own marker for CEF_EXPORT while keeping CEF_CALLBACK empty.
        "#define CEF_INCLUDE_INTERNAL_CEF_EXPORT_H_\n"
        f"#define CEF_EXPORT {EXPORT_MARK}\n"
        "#define CEF_CALLBACK\n" + capi_source
    )
    result = subprocess.run(
        ["xcrun", "clang", "-E", "-P", "-x", "c", "-std=c11", f"-I{INCLUDE}", "-"],
        input=source,
        capture_output=True,
        text=True,
    )
    if result.returncode != 0:
        sys.exit(f"generate-bindings: preprocessing failed:\n{result.stderr}")
    return result.stdout


def split_params(params):
    parts, depth, current = [], 0, ""
    for ch in params:
        if ch == "," and depth == 0:
            parts.append(current.strip())
            current = ""
            continue
        depth += ch in "([{"
        depth -= ch in ")]}"
        current += ch
    if current.strip():
        parts.append(current.strip())
    return parts


def parse_exports(preprocessed):
    text = re.sub(r"\s+", " ", preprocessed)
    symbols, skipped = {}, []
    pattern = re.compile(rf"{EXPORT_MARK}\s+([^;{{}}]+?)\s*\(([^;]*?)\)\s*;")
    for match in pattern.finditer(text):
        head, params = match.group(1).strip(), match.group(2).strip()
        name_match = re.search(r"([A-Za-z_][A-Za-z0-9_]*)$", head)
        if not name_match:
            continue
        name = name_match.group(1)
        return_type = head[: name_match.start()].strip()
        if "(" in params or "..." in params:
            skipped.append(name)  # function-pointer or variadic parameter
            continue
        if params in ("", "void"):
            args = ""
            params = "void"
        else:
            names = []
            for param in split_params(params):
                param_name = re.search(r"([A-Za-z_][A-Za-z0-9_]*)\s*(\[\s*\])?$", param)
                if not param_name:
                    names = None
                    break
                names.append(param_name.group(1))
            if names is None:
                skipped.append(name)
                continue
            args = ", ".join(names)
        symbols[name] = (return_type, params, args)
    return symbols, skipped


def render_symbols_header(symbols):
    lines = [
        GENERATED_BANNER,
        "//\n// Every cef_* global exported by the framework at the pinned\n"
        "// CEF_API_VERSION, as CCEF_SYM(return_type, name, (params), (args)).\n"
        "// ccef_loader.c expands this into lazily-bound trampolines.\n\n",
    ]
    for name in sorted(symbols):
        return_type, params, args = symbols[name]
        lines.append(f"CCEF_SYM({return_type}, {name}, ({params}), ({args}))\n")
    return "".join(lines)


def main():
    check = "--check" in sys.argv[1:]
    capi_source = render_capi_header()
    symbols, skipped = parse_exports(preprocess(capi_source))
    if not symbols:
        sys.exit("generate-bindings: found no exported symbols — header layout changed?")
    outputs = {CAPI_H: capi_source, SYMBOLS_H: render_symbols_header(symbols)}

    stale = [p for p, text in outputs.items() if not p.exists() or p.read_text() != text]
    if check:
        if stale:
            names = ", ".join(p.name for p in stale)
            sys.exit(f"generate-bindings: {names} out of date — run Scripts/generate-bindings.py")
        print(f"generate-bindings: up to date ({len(symbols)} symbols)")
        return
    for path in stale:
        path.write_text(outputs[path])
    print(f"generate-bindings: {len(symbols)} symbols, {len(capi_headers())} capi headers"
          + (f", skipped: {', '.join(skipped)}" if skipped else ""))


if __name__ == "__main__":
    main()
