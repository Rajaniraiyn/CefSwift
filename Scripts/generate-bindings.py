#!/usr/bin/env python3
"""Regenerates the CCef C bridge from the vendored CEF headers.

Outputs (both are generated files — never edit them by hand):

  Sources/CCef/include/ccef_capi.h     umbrella #include of every C API header
  Sources/CCef/include/ccef_symbols.h  X-macro list of every exported cef_* function

The symbol list is produced by running the real C preprocessor over the
umbrella header at the CEF_API_VERSION pinned in ccef_config.h, then collecting
every declaration marked CEF_EXPORT. That makes API-version gating exact: a
function the pinned version does not expose is never declared, so never bound.

  Scripts/generate-bindings.py                    # rewrite the generated files
  Scripts/generate-bindings.py --check            # exit 1 if they are out of date (CI)
  Scripts/generate-bindings.py --api-version latest|<number>
                                                  # move the pin, then regenerate
  Scripts/generate-bindings.py --check --framework <path>
                                                  # also require every bound symbol
                                                  # to be exported by that binary

Every run that writes prints which symbols were added, removed or changed
compared with the previous ccef_symbols.h; --summary <file> also writes that
as Markdown (Scripts/update-cef.py puts it in the pull-request description).
--include <dir> runs against a copy of Sources/CCef/include (update-cef.py
stages its work there so a failure never leaves the tree half-updated).
"""

import argparse
import os
import re
import subprocess
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
DEFAULT_INCLUDE = ROOT / "Sources" / "CCef" / "include"

# Internal headers that are C-safe and declare types or exported functions.
INTERNAL_HEADERS = [
    "include/cef_api_hash.h",
    "include/cef_version_info.h",
    "include/cef_command_ids.h",
    "include/cef_id_mappers.h",
    "include/cef_pack_strings.h",
    "include/internal/cef_string.h",
    "include/internal/cef_string_list.h",
    "include/internal/cef_string_map.h",
    "include/internal/cef_string_multimap.h",
    "include/internal/cef_time.h",
    "include/internal/cef_types.h",
    "include/internal/cef_logging_internal.h",
    "include/internal/cef_thread_internal.h",
    "include/internal/cef_trace_event_internal.h",
]

# Test-only C API; never shipped to embedders.
EXCLUDED_DIRS = {"test"}

GENERATED_BANNER = "// GENERATED by Scripts/generate-bindings.py — do not edit.\n"

EXPORT_MARK = "CCEF_EXPORT_MARK"

# CEF's placeholder versions for unreleased API (cef_api_hash.h). Pinning to
# them would make the C surface change with every CEF build.
UNRELEASED_API_VERSIONS = {999998, 999999}

PIN_PATTERN = re.compile(r"^(#define CEF_API_VERSION )(\d+)\s*$", re.M)
SYMBOL_LINE = re.compile(r"^CCEF_SYM\((.*), ([A-Za-z_][A-Za-z0-9_]*), \(", re.M)


def fail(message):
    sys.exit(f"generate-bindings: {message}")


# --- API version pin ---------------------------------------------------------


def read_pin(include):
    match = PIN_PATTERN.search((include / "ccef_config.h").read_text())
    if not match:
        fail(f"no '#define CEF_API_VERSION <number>' in {include / 'ccef_config.h'}")
    return int(match.group(2))


def write_pin(include, version):
    config = include / "ccef_config.h"
    text = PIN_PATTERN.sub(lambda m: f"{m.group(1)}{version}", config.read_text(), count=1)
    write_atomically(config, text)


def released_api_versions(versions_header_text):
    """(released versions, oldest supported, newest released) from cef_api_versions.h."""
    defined = {int(v) for v in re.findall(r"^#define CEF_API_VERSION_(\d+) \1\s*$",
                                          versions_header_text, re.M)}
    bounds = dict(re.findall(r"^#define CEF_API_VERSION_(MIN|LAST) CEF_API_VERSION_(\d+)\s*$",
                             versions_header_text, re.M))
    if not defined or set(bounds) != {"MIN", "LAST"}:
        fail("cannot read the API versions from include/cef_api_versions.h — header layout changed?")
    oldest, newest = int(bounds["MIN"]), int(bounds["LAST"])
    released = sorted(v for v in defined - UNRELEASED_API_VERSIONS if oldest <= v <= newest)
    return released, oldest, newest


def resolve_api_version(request, released, oldest, newest):
    if request == "latest":
        return newest
    if not request.isdigit():
        fail(f"--api-version takes 'latest' or a number, not '{request}'")
    if int(request) not in released:
        fail(f"CEF_API_VERSION {request} is not a released version in these headers "
             f"(supported: {oldest}…{newest}; newest: {', '.join(map(str, released[-5:]))})")
    return int(request)


def validate_pin(pin, released, oldest, newest):
    if pin in released:
        return
    if pin < oldest:
        why = f"these headers dropped it (oldest supported is {oldest})"
    elif pin in UNRELEASED_API_VERSIONS:
        why = "it is CEF's moving NEXT/EXPERIMENTAL placeholder, not a released version"
    else:
        why = f"they do not define it (released: {', '.join(map(str, released[-5:]))})"
    fail(f"the pinned CEF_API_VERSION {pin} (ccef_config.h) cannot be used with the vendored "
         f"CEF headers: {why}.\n"
         f"  Move the pin deliberately with `Scripts/update-cef.py --api-version latest` "
         f"(newest is {newest}) or `--api-version <number>`,\n"
         f"  then adapt the Swift code to the C API changes it reports.")


# --- generation --------------------------------------------------------------


def capi_headers(include):
    capi = include / "include" / "capi"
    found = []
    for path in sorted(capi.rglob("*.h")):
        relative = path.relative_to(include)
        if EXCLUDED_DIRS & set(relative.parts):
            continue
        found.append(relative.as_posix())
    return found


def render_capi_header(include):
    lines = [
        GENERATED_BANNER,
        "// Umbrella include of the CEF C API at the pinned CEF_API_VERSION.\n",
        "#ifndef CCEF_CAPI_H_\n#define CCEF_CAPI_H_\n\n",
        '#include "ccef_config.h"\n\n',
    ]
    lines += [f'#include "{h}"\n' for h in INTERNAL_HEADERS if (include / h).exists()]
    lines.append("\n")
    lines += [f'#include "{h}"\n' for h in capi_headers(include)]
    lines.append("\n#endif  // CCEF_CAPI_H_\n")
    return "".join(lines)


def preprocess(include, capi_source):
    """Preprocesses the umbrella header, tagging exports with EXPORT_MARK."""
    source = (
        # cef_export.h is include-guarded; pre-defining the guard lets us supply
        # our own marker for CEF_EXPORT while keeping CEF_CALLBACK empty.
        "#define CEF_INCLUDE_INTERNAL_CEF_EXPORT_H_\n"
        f"#define CEF_EXPORT {EXPORT_MARK}\n"
        "#define CEF_CALLBACK\n" + capi_source
    )
    try:
        result = subprocess.run(
            ["xcrun", "clang", "-E", "-P", "-x", "c", "-std=c11", f"-I{include}", "-"],
            input=source, capture_output=True, text=True,
        )
    except FileNotFoundError:
        fail("xcrun not found — the bridge is generated with Apple clang (install the Xcode command line tools)")
    if result.returncode != 0:
        errors = [line for line in result.stderr.splitlines() if "error:" in line]
        fail("preprocessing the CEF headers failed:\n  " + "\n  ".join(errors[:10] or [result.stderr.strip()]))
    return result.stdout


def split_params(params):
    parts, depth, current = [], 0, ""
    for ch in params:
        if ch == "," and depth == 0:
            parts.append(current.strip())
            current = ""
            continue
        depth += ch in "([{"
        depth -= ch in ")]}"
        current += ch
    if current.strip():
        parts.append(current.strip())
    return parts


def parse_exports(preprocessed):
    text = re.sub(r"\s+", " ", preprocessed)
    symbols, skipped = {}, []
    pattern = re.compile(rf"{EXPORT_MARK}\s+([^;{{}}]+?)\s*\(([^;]*?)\)\s*;")
    for match in pattern.finditer(text):
        head, params = match.group(1).strip(), match.group(2).strip()
        name_match = re.search(r"([A-Za-z_][A-Za-z0-9_]*)$", head)
        if not name_match:
            continue
        name = name_match.group(1)
        return_type = head[: name_match.start()].strip()
        if "(" in params or "..." in params:
            skipped.append(name)  # function-pointer or variadic parameter
            continue
        if params in ("", "void"):
            args = ""
            params = "void"
        else:
            names = []
            for param in split_params(params):
                param_name = re.search(r"([A-Za-z_][A-Za-z0-9_]*)\s*(\[\s*\])?$", param)
                if not param_name:
                    names = None
                    break
                names.append(param_name.group(1))
            if names is None:
                skipped.append(name)
                continue
            args = ", ".join(names)
        symbols[name] = (return_type, params, args)
    return symbols, skipped


def symbol_line(name, signature):
    return_type, params, args = signature
    return f"CCEF_SYM({return_type}, {name}, ({params}), ({args}))"


def render_symbols_header(symbols):
    lines = [
        GENERATED_BANNER,
        "//\n// Every cef_* global exported by the framework at the pinned\n"
        "// CEF_API_VERSION, as CCEF_SYM(return_type, name, (params), (args)).\n"
        "// ccef_loader.c expands this into lazily-bound trampolines.\n\n",
    ]
    lines += [symbol_line(name, symbols[name]) + "\n" for name in sorted(symbols)]
    return "".join(lines)


# --- reporting ---------------------------------------------------------------


def read_symbol_lines(symbols_header_text):
    """{name: full CCEF_SYM line} from a generated ccef_symbols.h."""
    return {m.group(2): line for line in symbols_header_text.splitlines()
            for m in [SYMBOL_LINE.match(line)] if m}


def diff_symbols(before, after):
    """Names added, removed and changed (same name, new signature), each sorted."""
    added = sorted(set(after) - set(before))
    removed = sorted(set(before) - set(after))
    changed = sorted(n for n in set(before) & set(after) if before[n] != after[n])
    return added, removed, changed


def describe_diff(before, after, markdown):
    added, removed, changed = diff_symbols(before, after)
    if not (added or removed or changed):
        return f"C API: unchanged ({len(after)} functions)."
    counts = ", ".join(f"{n} {label}" for n, label in
                       ((len(added), "added"), (len(removed), "removed"), (len(changed), "changed")) if n)
    groups = [(label, names) for label, names in
              (("Added", added), ("Removed", removed), ("Signature changed", changed)) if names]
    if markdown:
        body = [f"- {label}: {', '.join(f'`{n}`' for n in names)}" for label, names in groups]
    else:
        body = [f"  {label}: {', '.join(names)}" for label, names in groups]
    return "\n".join([f"C API: {len(before)} → {len(after)} functions ({counts}).", *([""] if markdown else []), *body])


# --- framework audit ---------------------------------------------------------


def exported_names(framework):
    binary = Path(framework)
    if binary.suffix == ".framework":
        binary = binary / binary.stem
    if not binary.is_file():
        fail(f"no framework binary at {binary}")
    result = subprocess.run(["xcrun", "nm", "-gUj", str(binary)], capture_output=True, text=True)
    if result.returncode != 0:
        fail(f"nm failed for {binary}:\n{result.stderr}")
    return {line[1:] for line in result.stdout.split() if line.startswith("_")}, binary


def audit_framework(framework, names):
    exported, binary = exported_names(framework)
    missing = sorted(set(names) - exported)
    if missing:
        fail(f"{binary.name} does not export {len(missing)} bound function(s): {', '.join(missing)}.\n"
             "  The vendored headers do not match the pinned framework — re-run Scripts/update-cef.py.")
    print(f"generate-bindings: {binary.name} exports all {len(names)} bound functions")


# --- main --------------------------------------------------------------------


def write_atomically(path, text):
    temporary = path.with_name(path.name + ".tmp")
    temporary.write_text(text)
    os.replace(temporary, path)


def parse_arguments(argv):
    parser = argparse.ArgumentParser(description="Regenerates the CCef C bridge from the vendored CEF headers.")
    parser.add_argument("--check", action="store_true", help="exit 1 if the generated files are out of date")
    parser.add_argument("--api-version", metavar="latest|N", help="move the CEF_API_VERSION pin first")
    parser.add_argument("--framework", metavar="PATH", help="require every bound function to be exported by this binary")
    parser.add_argument("--summary", metavar="FILE", type=Path, help="write the symbol changes as Markdown")
    parser.add_argument("--include", metavar="DIR", type=Path, default=DEFAULT_INCLUDE,
                        help="the CCef include directory to work on (default: Sources/CCef/include)")
    arguments = parser.parse_args(argv)
    if arguments.check and arguments.api_version:
        parser.error("--check and --api-version cannot be combined")
    return arguments


def main(argv=None):
    arguments = parse_arguments(sys.argv[1:] if argv is None else argv)
    include = arguments.include.resolve()
    capi_h, symbols_h = include / "ccef_capi.h", include / "ccef_symbols.h"

    released, oldest, newest = released_api_versions(
        (include / "include" / "cef_api_versions.h").read_text())
    pin = read_pin(include)
    if arguments.api_version:
        target = resolve_api_version(arguments.api_version, released, oldest, newest)
        if target != pin:
            write_pin(include, target)
            print(f"generate-bindings: CEF_API_VERSION {pin} → {target}")
            pin = target
    validate_pin(pin, released, oldest, newest)

    capi_source = render_capi_header(include)
    symbols, skipped = parse_exports(preprocess(include, capi_source))
    if not symbols:
        fail("found no exported symbols — header layout changed?")
    outputs = {capi_h: capi_source, symbols_h: render_symbols_header(symbols)}
    stale = [p for p, text in outputs.items() if not p.exists() or p.read_text() != text]

    if arguments.check:
        if stale:
            fail(f"{', '.join(p.name for p in stale)} out of date — run Scripts/generate-bindings.py")
        print(f"generate-bindings: up to date ({len(symbols)} symbols at CEF_API_VERSION {pin})")
    else:
        before = read_symbol_lines(symbols_h.read_text()) if symbols_h.exists() else {}
        after = {name: symbol_line(name, signature) for name, signature in symbols.items()}
        for path in stale:
            write_atomically(path, outputs[path])
        print(f"generate-bindings: {len(symbols)} symbols at CEF_API_VERSION {pin}, "
              f"{len(capi_headers(include))} capi headers"
              + (f", skipped: {', '.join(skipped)}" if skipped else ""))
        print(describe_diff(before, after, markdown=False))
        if arguments.summary:
            arguments.summary.write_text(describe_diff(before, after, markdown=True) + "\n")

    if arguments.framework:
        audit_framework(arguments.framework, symbols)


if __name__ == "__main__":
    main()
